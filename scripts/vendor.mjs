import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkgDir = join(root, 'node_modules', 'mermaid');
const outDir = join(root, 'vendor');

if (!existsSync(pkgDir)) {
  console.error('Mermaid is not installed. Run "npm install" first, then "npm run vendor".');
  process.exit(1);
}

const { version } = JSON.parse(await readFile(join(pkgDir, 'package.json'), 'utf8'));

await mkdir(outDir, { recursive: true });
await copyFile(join(pkgDir, 'dist', 'mermaid.min.js'), join(outDir, 'mermaid.min.js'));
await copyFile(join(pkgDir, 'LICENSE'), join(outDir, 'mermaid.LICENSE'));
await writeFile(
  join(outDir, 'README.md'),
  `# Vendored code

- \`mermaid.min.js\`: [Mermaid](https://mermaid.js.org/) ${version}, the \`mermaid\` npm package.
- \`mermaid.LICENSE\`: its licence. Mermaid is MIT licensed.

Generated by npm run vendor; do not edit.
`,
);

console.log(`Copied Mermaid ${version} into vendor/.`);
